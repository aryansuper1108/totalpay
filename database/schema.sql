CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('ADMIN','MANAGER','EMPLOYEE')),
  department TEXT NOT NULL,
  team_id BIGINT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  department TEXT NOT NULL,
  manager_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  owner_id BIGINT NOT NULL REFERENCES users(id),
  team_id BIGINT REFERENCES teams(id) ON DELETE SET NULL,
  created_by BIGINT NOT NULL REFERENCES users(id),
  status TEXT NOT NULL DEFAULT 'TODO' CHECK (status IN ('TODO','IN_PROGRESS','ON_HOLD','BLOCKED','DONE')),
  priority TEXT NOT NULL DEFAULT 'MEDIUM' CHECK (priority IN ('LOW','MEDIUM','HIGH')),
  due_date DATE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS task_collaborators (
  task_id BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY(task_id,user_id)
);
CREATE TABLE IF NOT EXISTS requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mid TEXT, merchant_name TEXT, request_date DATE, description TEXT, platform TEXT,
  requester TEXT, developer TEXT, approver TEXT, status TEXT, test_status TEXT,
  environment TEXT, checker TEXT, release_date DATE,
  created_by BIGINT REFERENCES users(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_users_team_active ON users(team_id,active);
CREATE INDEX IF NOT EXISTS idx_tasks_owner_due ON tasks(owner_id,due_date);
CREATE INDEX IF NOT EXISTS idx_tasks_team_due ON tasks(team_id,due_date);
CREATE INDEX IF NOT EXISTS idx_task_collaborators_user ON task_collaborators(user_id);
CREATE INDEX IF NOT EXISTS idx_requests_created ON requests(created_at DESC);

